import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { inferenceSchema } from '@beetle/contracts/tooling/inference';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceDir = join(root, 'api/v2');
const outputDir = join(root, 'src/api/generated');
const banner = '// Generated by contracts/scripts/generate-api.ts; edit api/v2 sources.\n';
const internal = new Set(['MutationIntent', 'VersionedIntent', 'SettingsIdentity']);
interface Source { path: string; file: string; title: string; id: string; value: Record<string, unknown>; hash: string }
interface Message { name: string; source: Source; reference: string }
interface Operation {
  name: string; method: string; path: string; request?: string; response: string;
  successStatus: number; error: string; params?: string; query?: string;
}

async function source(path: string): Promise<Source> {
  const raw = await readFile(join(root, path), 'utf8');
  const value = JSON.parse(raw) as Record<string, unknown>;
  if (typeof value.title !== 'string' || !/^[A-Z][A-Za-z]+$/.test(value.title)) throw new Error(`Invalid title: ${path}`);
  if (typeof value.$id !== 'string') throw new Error(`Missing schema ID: ${path}`);
  return { path, file: path.split('/').at(-1) ?? '', title: value.title, id: value.$id,
    value, hash: createHash('sha256').update(raw).digest('hex') };
}

async function sources(): Promise<Source[]> {
  const names = (await readdir(sourceDir)).filter(file => file.endsWith('.schema.json')).sort();
  const schemas = await Promise.all(names.map(file => source(`api/v2/${file}`)));
  const runner = await Promise.all(['common', 'engine-result', 'result-evidence', 'result-execution',
    'agent-event', 'event-envelope', 'wrapper-events', 'supervisor-events']
    .map(name => source(`runner/v1/${name}.schema.json`)));
  return [...runner, ...schemas];
}

function messages(schemas: Source[]): Message[] {
  const result = schemas.filter(schema => schema.path.startsWith('api/')).flatMap(schema =>
    Object.keys(schema.value.$defs as object).filter(name => !internal.has(name)).map(name =>
      ({ name, source: schema, reference: `${schema.id}#/$defs/${name}` })));
  const unique = new Set(result.map(message => message.name));
  if (unique.size !== result.length) throw new Error('Duplicate API type name');
  if (new Set(schemas.map(schema => schema.id)).size !== schemas.length) throw new Error('Duplicate schema ID');
  return result;
}

function parameterNames(name: string | undefined, types: Message[]): string[] {
  const message = types.find(type => type.name === name);
  if (!message) return [];
  const definitions = message.source.value.$defs as Record<string, { properties: object }>;
  return Object.keys(definitions[message.name]?.properties ?? {}).sort();
}

function validateOperation(operation: Operation, types: Message[]): void {
  const names = new Set(types.map(message => message.name));
  const referenced = [operation.request, operation.response, operation.error, operation.params, operation.query];
  if (referenced.some(name => name !== undefined && !names.has(name))) throw new Error('Unknown operation schema');
  if (!/^[a-z][A-Za-z]+$/.test(operation.name) || !['GET', 'POST', 'PATCH', 'DELETE'].includes(operation.method)) {
    throw new Error('Invalid operation name or method');
  }
  if (!operation.path.startsWith('/api/v2/') || ![200, 201, 202].includes(operation.successStatus)) {
    throw new Error('Invalid operation path or success status');
  }
  const placeholders = [...operation.path.matchAll(/\{([A-Za-z]+)\}/g)].map(match => match[1]).sort();
  if (JSON.stringify(placeholders) !== JSON.stringify(parameterNames(operation.params, types))) {
    throw new Error('Operation parameter mismatch');
  }
}

function catalogueOutput(schemas: Source[], types: Message[]): string {
  return banner + `import { freezeSchema } from '../../freeze.js';\n` + schemas.map(schema =>
    `import { schema as ${schema.title} } from '${schema.path.startsWith('runner/') ? `../../generated/${schema.file.replace('.schema.json', '.js')}` : `./${schema.file.replace('.schema.json', '.js')}`}';`).join('\n')
    + '\n/** Complete reference closure; runner result schemas are shared, never copied. */\n'
    + `export const apiSchemas = freezeSchema([${schemas.map(schema => schema.title).join(', ')}] as const);\n`
    + 'export const apiMessageSchemas = freezeSchema({\n' + types.map(message =>
      `  ${message.name}: { $ref: '${message.reference}' },`).join('\n') + '\n} as const);\n';
}

function typeOutput(types: Message[]): string {
  const bySource = [...new Set(types.map(message => message.source.file))];
  return banner + `import type { FromSchema } from 'json-schema-to-ts';\n` + bySource.map((file, index) =>
    `import type { projections as S${index} } from './${file.replace('.schema.json', '.inference.js')}';`).join('\n')
    + '\n' + types.map(message => `export type ${message.name} = FromSchema<typeof S${bySource.indexOf(message.source.file)}.${message.name}>;`).join('\n')
    + '\nexport interface ApiTypes {\n' + types.map(message => `  ${message.name}: ${message.name};`).join('\n') + '\n}\n';
}

function reference(operations: Operation[]): string {
  return '# Generated API v2 namespace/settings reference\n\n'
    + 'Sources: `contracts/api/v2`; runtime entrypoint: `contracts/src/api/index.ts`.\n'
    + 'Schema catalogue is complete, including runner common exactly once. These are route descriptors, not implemented routes or an HTTP client.\n\n'
    + '| Method | Route | Params | Query | Request | Success | Response |\n| --- | --- | --- | --- | --- | --- | --- |\n'
    + operations.map(op => `| ${op.method} | ${op.path} | ${op.params ?? 'none'} | ${op.query ?? 'none'} | ${op.request ?? 'none'} | ${op.successStatus} | ${op.response} |`).join('\n')
    + '\n\nAll errors use ApiError. UUID path parameters are validated before URL encoding.\n'
    + 'List queries require an integer limit 1–100 and optional opaque string cursor; HTTP query parsing belongs to the transport adapter.\n'
    + 'Organisation retention operations also accept a workspace scope within that route organisation; installation retention operations require installation scope.\n'
    + 'See ../CONTEXT.md for mandatory semantic checks and settings/retention behavior.\n';
}

function schemaOutputs(schemas: Source[], types: Message[]): Map<string, string> {
  const catalogue = new Map(schemas.map(schema => [schema.id, schema.value]));
  const output = new Map<string, string>();
  for (const schema of schemas.filter(schema => schema.path.startsWith('api/'))) {
    output.set(schema.file.replace('.schema.json', '.ts'), banner
      + `// Source: ${schema.path}; sha256:${schema.hash}\nimport { freezeSchema } from '../../freeze.js';\n`
      + `export const schema = freezeSchema(${JSON.stringify(schema.value)} as const);\n`);
    const projections = Object.fromEntries(types.filter(message => message.source === schema).map(message =>
      [message.name, inferenceSchema({ $ref: message.reference }, catalogue)]));
    output.set(schema.file.replace('.schema.json', '.inference.ts'), banner
      + `// Reference-expanded projection of ${schema.path}; full source hashes: manifest.json.\n`
      + `export const projections = ${JSON.stringify(projections)} as const;\n`);
  }
  return output;
}

async function outputs(schemas: Source[]): Promise<Map<string, string>> {
  const types = messages(schemas);
  const raw = await readFile(join(sourceDir, 'http-operations.json'), 'utf8');
  const operations = JSON.parse(raw) as Operation[];
  for (const operation of operations) validateOperation(operation, types);
  if (new Set(operations.map(op => op.name)).size !== operations.length) throw new Error('Duplicate operation name');
  if (new Set(operations.map(op => `${op.method} ${op.path}`)).size !== operations.length) throw new Error('Duplicate route');
  const output = schemaOutputs(schemas, types);
  output.set('schemas.ts', catalogueOutput(schemas, types));
  output.set('types.ts', typeOutput(types));
  output.set('operations.ts', banner + `import { freezeSchema } from '../../freeze.js';\n`
    + `export const apiOperations = freezeSchema(${JSON.stringify(operations)} as const);\n`
    + 'export type ApiOperation = typeof apiOperations[number];\n');
  output.set('reference.md', reference(operations));
  output.set('manifest.json', JSON.stringify({ generator: 'contracts/scripts/generate-api.ts',
    sources: Object.fromEntries(schemas.map(schema => [schema.path, schema.hash])),
    operationsSha256: createHash('sha256').update(raw).digest('hex'),
    outputs: [...output.keys(), 'manifest.json'].sort() }, null, 2) + '\n');
  return output;
}

async function generate(): Promise<void> {
  const output = await outputs(await sources());
  const check = process.argv.includes('--check');
  if (!check) await mkdir(outputDir, { recursive: true });
  const actualFiles = await readdir(outputDir).catch((error: NodeJS.ErrnoException) => {
    if (error.code === 'ENOENT') return [];
    throw error;
  });
  const unexpected = actualFiles.filter(file => !output.has(file));
  if (unexpected.length) throw new Error(`Unexpected generated files: ${unexpected.join(', ')}`);
  for (const [file, content] of output) {
    const path = join(outputDir, file);
    if (check) {
      const actual = await readFile(path, 'utf8').catch((error: NodeJS.ErrnoException) => {
        if (error.code === 'ENOENT') return undefined;
        throw error;
      });
      if (actual !== content) throw new Error(`Generated drift: contracts/src/api/generated/${file}`);
    } else await writeFile(path, content);
  }
  console.log(`${check ? 'Checked' : 'Generated'} ${output.size} API contract outputs.`);
}
await generate();
