import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { inferenceSchema } from './inference.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceDir = join(root, 'runner/v1');
const outputDir = join(root, 'src/generated');
const banner = '// Generated by contracts/scripts/generate.ts; edit runner/v1 sources.\n';
interface SchemaSource { file: string; title: string; value: Record<string, unknown>; hash: string }
interface Operation { name: string; method: string; path: string; request?: string; response: string; successStatus: number; cursor?: boolean }

function isMessage(schema: SchemaSource): boolean {
  return ['$ref', 'type', 'oneOf', 'anyOf', 'allOf'].some(keyword => keyword in schema.value);
}

async function sources(): Promise<SchemaSource[]> {
  const files = (await readdir(sourceDir)).filter(file => file.endsWith('.schema.json')).sort();
  return Promise.all(files.map(async file => {
    const raw = await readFile(join(sourceDir, file), 'utf8');
    const value = JSON.parse(raw) as Record<string, unknown>;
    if (typeof value.title !== 'string' || !/^[A-Z][A-Za-z]+$/.test(value.title)) throw new Error(`Invalid title in ${file}`);
    return { file, title: value.title, value, hash: createHash('sha256').update(raw).digest('hex') };
  }));
}

function typeOutput(schemas: SchemaSource[]): string {
  const common = schemas.find(schema => schema.title === 'Common');
  if (!common) throw new Error('Missing common definitions');
  const definitions = Object.keys(common.value.$defs as object).map(name =>
    `export type ${name[0]?.toUpperCase()}${name.slice(1)} = FromSchema<typeof CommonSchema.$defs.${name}, { references: [...typeof schemas] }>;`);
  const declarations = schemas.filter(isMessage).map(schema =>
    `export type ${schema.title} = FromSchema<typeof ${schema.title}Schema, { references: [...typeof schemas] }>;`);
  return banner + `import type { FromSchema } from 'json-schema-to-ts';\n`
    + `import type { schemas } from './schemas.js';\n`
    + `import type { schema as CommonSchema } from './common.js';\n`
    + schemas.filter(isMessage).map(schema =>
      `import type { schema as ${schema.title}Schema } from './${schema.file.replace('.schema.json', '.inference.js')}';`).join('\n')
    + '\n' + definitions.join('\n') + '\n' + declarations.join('\n') + '\n'
    + 'export interface ProtocolTypes {\n' + schemas.filter(isMessage).map(schema =>
      `  ${schema.title}: ${schema.title};`).join('\n') + '\n}\n';
}

function clientMethod(operation: Operation): string {
  const hasId = operation.path.includes('{attemptId}');
  const args = [hasId ? 'attemptId: string' : '', operation.request ? `body: ${operation.request}` : '',
    operation.cursor ? 'after: number' : '', 'signal?: AbortSignal'].filter(Boolean).join(', ');
  const request = operation.request ? `, request: '${operation.request}'` : '';
  const cursor = operation.cursor ? ', cursor: true' : '';
  const input = [hasId ? 'attemptId' : '', operation.cursor ? 'after' : '', operation.request ? 'body' : '', 'signal'].filter(Boolean);
  return `    ${operation.name}: (${args}) => invokeRunner(transport, { method: '${operation.method}', path: '${operation.path}', response: '${operation.response}', successStatus: ${operation.successStatus}${request}${cursor} }, { ${input.join(', ')} }),`;
}

function reference(schemas: SchemaSource[], operations: Operation[]): string {
  return '# Generated runner v1 JSON API reference\n\n'
    + 'Source: `contracts/runner/v1`; regenerate with `node --import tsx contracts/scripts/generate.ts`.\n\n'
    + '| Method | Route | Request | Success | Response |\n| --- | --- | --- | --- | --- |\n'
    + operations.map(operation => `| ${operation.method} | ${operation.path} | ${operation.request ?? 'none'} | ${operation.successStatus} | ${operation.response} |`).join('\n')
    + '\n\nAll error replies use ProtocolError. Events accept the `after` cursor query.\n'
    + 'GET sealed artifact streams/ranges belong to the artifact transport owner.\n\n'
    + 'Shipped schemas: ' + schemas.map(schema => schema.title).join(', ') + '.\n';
}

async function outputs(schemas: SchemaSource[]): Promise<Map<string, string>> {
  const operationsRaw = await readFile(join(sourceDir, 'http-operations.json'), 'utf8');
  const operations = JSON.parse(operationsRaw) as Operation[];
  const output = new Map(schemas.map(schema => [schema.file.replace('.schema.json', '.ts'),
    banner + `// Source: runner/v1/${schema.file}; sha256:${schema.hash}\n`
      + `import { freezeSchema } from '../freeze.js';\nexport const schema = freezeSchema(${JSON.stringify(schema.value)} as const);\n`]));
  const catalogue = new Map(schemas.map(schema => [String(schema.value.$id), schema.value]));
  for (const schema of schemas.filter(isMessage)) {
    output.set(schema.file.replace('.schema.json', '.inference.ts'), banner
      + `// Reference-expanded typing projection of runner/v1/${schema.file}; full source hashes: manifest.json.\n`
      + `import { freezeSchema } from '../freeze.js';\nexport const schema = freezeSchema(${JSON.stringify(inferenceSchema(schema.value, catalogue))} as const);\n`);
  }
  output.set('schemas.ts', banner + `import { freezeSchema } from '../freeze.js';\n` + schemas.map(schema =>
    `import { schema as ${schema.title} } from './${schema.file.replace('.schema.json', '.js')}';`).join('\n')
    + '\nexport const schemas = freezeSchema([' + schemas.map(schema => schema.title).join(', ') + '] as const);\n'
    + 'export const messageSchemas = freezeSchema({ ' + schemas.filter(isMessage).map(schema => schema.title).join(', ') + ' } as const);\n');
  output.set('types.ts', typeOutput(schemas));
  const requestTypes = [...new Set(operations.flatMap(operation => operation.request ? [operation.request] : []))];
  output.set('client.ts', banner + `import type { ${requestTypes.join(', ')} } from './types.js';\n`
    + `import type { RunnerTransport } from '../http.js';\n`
    + `import { invokeRunner } from '../client-call.js';\n`
    + 'export function createRunnerClient(transport: RunnerTransport) {\n  return {\n'
    + operations.map(clientMethod).join('\n') + '\n  };\n}\n');
  output.set('reference.md', reference(schemas, operations));
  output.set('manifest.json', JSON.stringify({ generator: 'contracts/scripts/generate.ts',
    sources: Object.fromEntries(schemas.map(schema => [`runner/v1/${schema.file}`, schema.hash])),
    operationsSha256: createHash('sha256').update(operationsRaw).digest('hex'),
    outputs: [...output.keys(), 'manifest.json'].sort() }, null, 2) + '\n');
  return output;
}

async function generate(): Promise<void> {
  const output = await outputs(await sources());
  const check = process.argv.includes('--check');
  await mkdir(outputDir, { recursive: true });
  const unexpected = (await readdir(outputDir)).filter(file => !output.has(file));
  if (unexpected.length) throw new Error(`Unexpected generated files: ${unexpected.join(', ')}`);
  for (const [file, content] of output) {
    const path = join(outputDir, file);
    if (check) {
      const actual = await readFile(path, 'utf8').catch(() => undefined);
      if (actual !== content) throw new Error(`Generated drift: contracts/src/generated/${file}`);
    } else await writeFile(path, content);
  }
  console.log(`${check ? 'Checked' : 'Generated'} ${output.size} contract outputs.`);
}
await generate();
